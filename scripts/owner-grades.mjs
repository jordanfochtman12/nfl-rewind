// Builds src/lib/game/data/ownerGrades.ts from the owner's QB board (scripts/qb-grades.json):
// each quarterback's overall on draft day and the peak his career climbs to.
import { readFileSync, writeFileSync } from "node:fs";

const grades = JSON.parse(readFileSync(new URL("./qb-grades.json", import.meta.url), "utf8"));
const rows = Object.entries(grades)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, g]) => `  ${JSON.stringify(k)}: { d: ${g.draftOvr}, p: ${Math.max(g.peak, g.draftOvr)} },`);
const out = `// Generated by scripts/owner-grades.mjs from scripts/qb-grades.json. Do not edit by hand.
/** The owner's grades, keyed "draftYear|first|last": overall on draft day (d) and career peak (p). */
export const OWNER_GRADES: Record<string, { d: number; p: number }> = {
${rows.join("\n")}
};
`;
writeFileSync(new URL("../src/lib/game/data/ownerGrades.ts", import.meta.url), out);
console.log(`${rows.length} owner grades`);
