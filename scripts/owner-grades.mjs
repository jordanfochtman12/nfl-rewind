// Builds src/lib/game/data/ownerGrades.ts from the owner's draft boards: the QB board
// (scripts/qb-grades.json) and the board for every other position (scripts/board-grades.json).
// Each player's overall on draft day and the peak his career climbs to.
import { readFileSync, writeFileSync } from "node:fs";

const read = (f) => JSON.parse(readFileSync(new URL(f, import.meta.url), "utf8"));
const grades = { ...read("./qb-grades.json"), ...read("./board-grades.json") };
const rows = Object.entries(grades)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, g]) => `  ${JSON.stringify(k)}: { d: ${g.draftOvr}, p: ${Math.max(g.peak, g.draftOvr)} },`);
const out = `// Generated by scripts/owner-grades.mjs from scripts/qb-grades.json and scripts/board-grades.json. Do not edit by hand.
/** The owner's grades, keyed "draftYear|first|last": overall on draft day (d) and career peak (p). */
export const OWNER_GRADES: Record<string, { d: number; p: number }> = {
${rows.join("\n")}
};
`;
writeFileSync(new URL("../src/lib/game/data/ownerGrades.ts", import.meta.url), out);
console.log(`${rows.length} owner grades`);
