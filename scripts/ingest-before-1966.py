#!/usr/bin/env python3
"""History mode's starting ledger: every franchise's real record and every series before 1966.

From the FiveThirtyEight game file (NFL 1920-1965, AFL 1960-1965; the AAFC is left out, as
the league's own record book leaves it out). For each club still in the league in 1966:
regular-season and playoff wins, losses and ties, and league championships; for each pair of
those clubs, the head-to-head series and their last meeting. History mode starts its ledgers
here, so a 1966 series between the Bears and Packers already has 40-plus years behind it.

Championships before the first title game (1933) went by the standings; the ones won by
clubs still playing are listed by hand below (1932's was decided by an indoor playoff the
league counted as a regular-season game).

Writes src/lib/game/data/history/before1966.ts.
Re-run: python3 scripts/ingest-before-1966.py
"""
from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "schedules" / "fivethirtyeight_nfl_games.csv"
OUT = ROOT / "src" / "lib" / "game" / "data" / "history" / "before1966.ts"

CLUB = {
    "CHI": "chi", "GB": "gnb", "NYG": "nyg", "ARI": "crd", "DET": "det", "WSH": "was", "PHI": "phi",
    "PIT": "pit", "LAR": "ram", "CLE": "cle", "SF": "sfo", "IND": "clt", "DAL": "dal", "MIN": "min",
    "LAC": "sdg", "BUF": "buf", "TEN": "oti", "NE": "nwe", "KC": "kan", "OAK": "rai", "NYJ": "nyj", "DEN": "den",
}
AFL = {"sdg", "buf", "oti", "nwe", "kan", "rai", "nyj", "den"}
# League champions before the 1933 title game, among clubs still playing in 1966.
EARLY_TITLES = {1921: "chi", 1925: "crd", 1927: "nyg", 1929: "gnb", 1930: "gnb", 1931: "gnb", 1932: "chi"}


def main() -> None:
    rec = defaultdict(lambda: [0, 0, 0, 0, 0])  # w, l, t, playoff w, playoff l
    titles: dict[str, list[int]] = defaultdict(list)
    series: dict[tuple[str, str], list] = {}
    last_game: dict[tuple[int, str], tuple[str, str, str]] = {}  # (season, league) -> date, winner
    for r in csv.DictReader(open(SRC, encoding="utf-8")):
        y = int(r["season"])
        if y >= 1966:
            continue
        a, b = CLUB.get(r["team1"]), CLUB.get(r["team2"])
        # The AAFC (1946-49) isn't in the league's record book: Cleveland and San Francisco
        # count from 1950.
        if r["team1"] in ("CLE", "SF") and y < 1950 or r["team2"] in ("CLE", "SF") and y < 1950:
            continue
        s1, s2 = int(r["score1"]), int(r["score2"])
        playoff = r["playoff"] == "1"
        winner = a if s1 > s2 else b if s2 > s1 else None
        if playoff and a and b:
            league = "afl" if a in AFL else "nfl"
            d = r["date"]
            if (y, league) not in last_game or d > last_game[(y, league)][0]:
                last_game[(y, league)] = (d, winner or "", "")
        for me, them, us, op in ((a, b, s1, s2), (b, a, s2, s1)):
            if not me:
                continue
            k = 3 if playoff else 0
            if us > op:
                rec[me][k] += 1
            elif us < op:
                rec[me][k + 1 if playoff else 1] += 1
            elif not playoff:
                rec[me][2] += 1
        if not (a and b):
            continue
        lo, hi = sorted((a, b))
        s = series.setdefault((lo, hi), [0, 0, 0, 0, "", "", 0])
        if winner == lo:
            s[0] += 1
        elif winner == hi:
            s[1] += 1
        else:
            s[2] += 1
        s[3] = y
        s[4] = winner or ""
        s[5] = f"{max(s1, s2)}-{min(s1, s2)}"
        s[6] = 1 if playoff else 0
    for y, t in EARLY_TITLES.items():
        titles[t].append(y)
    for (y, _league), (_d, w, _) in sorted(last_game.items()):
        if w:
            titles[w].append(y)
    lines = [
        "/** Auto-generated by scripts/ingest-before-1966.py (FiveThirtyEight game file). Do not hand-edit. */",
        "/** Per club, before 1966: wins, losses, ties, playoff wins, playoff losses, then league titles by year. */",
        "export const FRANCHISE_BEFORE: Record<string, [number, number, number, number, number, number[]]> = {",
    ]
    for t in sorted(rec):
        w, l, ti, pw, pl = rec[t]
        lines.append(f"  {t}: [{w}, {l}, {ti}, {pw}, {pl}, [{', '.join(map(str, sorted(titles[t])))}]],")
    lines.append("};")
    lines.append("/** Per pair 'a|b' (a < b), before 1966: a's wins, b's wins, ties, then the last meeting: year, winner, score, playoff (1). */")
    lines.append("export const SERIES_BEFORE: Record<string, [number, number, number, number, string, string, number]> = {")
    for (a, b), s in sorted(series.items()):
        lines.append(f'  "{a}|{b}": [{s[0]}, {s[1]}, {s[2]}, {s[3]}, "{s[4]}", "{s[5]}", {s[6]}],')
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    for t in ("chi", "gnb", "nyg", "cle", "clt", "buf"):
        print(t, rec[t], titles[t])
    print("chi|gnb", series[("chi", "gnb")])


if __name__ == "__main__":
    main()
