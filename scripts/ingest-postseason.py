#!/usr/bin/env python3
"""Build the real postseason for every season the game can play: the playoff field, the
champion, the runner-up and the title-game score. Powers "real history vs your timeline".

Sources (cached in data/schedules): FiveThirtyEight for 1966-1998, nflverse for 1999+.
The last postseason game of each season is its championship (the Super Bowl from 1966 on).

Writes src/lib/game/data/realPostseason.ts.

Re-run: python3 scripts/ingest-postseason.py
"""
from __future__ import annotations

import csv
import datetime as dt
import importlib.util
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "schedules"
OUT = ROOT / "src" / "lib" / "game" / "data" / "realPostseason.ts"

spec = importlib.util.spec_from_file_location("sched", ROOT / "scripts" / "ingest-schedules.py")
sched = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sched)  # type: ignore[union-attr]
CODE = sched.CODE
FIRST, LAST_538 = 1966, 1998


def main() -> None:
    games: dict[int, list[tuple]] = defaultdict(list)
    for r in csv.DictReader(open(SRC / "fivethirtyeight_nfl_games.csv")):
        y = int(r["season"])
        if FIRST <= y <= LAST_538 and r["playoff"] not in ("", "0"):
            games[y].append((dt.date.fromisoformat(r["date"]), CODE[r["team1"]], CODE[r["team2"]], int(r["score1"]), int(r["score2"])))
    for r in csv.DictReader(open(SRC / "nflverse_games.csv")):
        y = int(r["season"])
        if y <= LAST_538 or r["game_type"] == "REG" or r["home_score"] in ("", "NA"):
            continue
        games[y].append(
            (dt.date.fromisoformat(r["gameday"]), CODE[r["home_team"]], CODE[r["away_team"]], int(r["home_score"]), int(r["away_score"]))
        )

    lines = []
    for y in sorted(games):
        g = sorted(games[y], key=lambda x: x[0])
        d, h, a, hs, as_ = g[-1]
        champ, runner = (h, a) if hs > as_ else (a, h)
        field = sorted({t for x in g for t in (x[1], x[2])})
        lines.append(
            f'  {y}: {{ champ: "{champ}", runnerUp: "{runner}", score: "{max(hs, as_)}-{min(hs, as_)}", field: {field!r} }},'.replace("'", '"')
        )

    OUT.write_text(
        "/** Auto-generated by scripts/ingest-postseason.py (FiveThirtyEight 1966-1998, nflverse 1999+). */\n"
        "/** The real postseason: champion, runner-up, title-game score, and every playoff club. */\n"
        "export interface RealPostseason {\n  champ: string;\n  runnerUp: string;\n  score: string;\n  field: string[];\n}\n"
        "export const REAL_POSTSEASON: Record<number, RealPostseason> = {\n" + "\n".join(lines) + "\n};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(lines)} seasons")


if __name__ == "__main__":
    main()
