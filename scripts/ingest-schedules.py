#!/usr/bin/env python3
"""Build the real regular-season schedule for every season the game can play.

Sources (cached in data/schedules):
  fivethirtyeight_nfl_games.csv  FiveThirtyEight's game file, every NFL + AFL game since 1920
                                 (dates, home team, scores). Used for 1966-1998.
  nflverse_games.csv             nflverse schedule file, 1999-present, with official weeks,
                                 kickoff times and neutral sites.

Writes src/lib/game/data/realSchedules.ts.

Re-run: python3 scripts/ingest-schedules.py
"""
from __future__ import annotations

import csv
import datetime as dt
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "schedules"
OUT = ROOT / "src" / "lib" / "game" / "data" / "realSchedules.ts"

# Franchise codes -> engine TeamId. FiveThirtyEight uses one code per franchise across
# moves (IND = Colts, TEN = Oilers/Titans, BAL = Ravens); nflverse uses the code of the day.
CODE = {
    "ARI": "crd", "ATL": "atl", "BAL": "rav", "BUF": "buf", "CAR": "car", "CHI": "chi",
    "CIN": "cin", "CLE": "cle", "DAL": "dal", "DEN": "den", "DET": "det", "GB": "gnb",
    "HOU": "htx", "IND": "clt", "JAX": "jax", "KC": "kan", "LA": "ram", "LAR": "ram",
    "STL": "ram", "LAC": "sdg", "SD": "sdg", "LV": "rai", "OAK": "rai", "MIA": "mia",
    "MIN": "min", "NE": "nwe", "NO": "nor", "NYG": "nyg", "NYJ": "nyj", "PHI": "phi",
    "PIT": "pit", "SEA": "sea", "SF": "sfo", "TB": "tam", "TEN": "oti", "WSH": "was",
    "WAS": "was",
}

FIRST, LAST_538 = 1966, 1998


def flag_for(day: dt.date, gametime: str = "") -> str:
    """M = Monday night, T = Thursday, S = Saturday, F = Friday, N = Sunday night, '' = Sunday day."""
    wd = day.weekday()  # Mon=0
    if wd == 0:
        return "M"
    if wd == 3:
        return "T"
    if wd == 5:
        return "S"
    if wd == 4:
        return "F"
    if wd == 6 and gametime and gametime >= "19:00":
        return "N"
    return ""


def main() -> None:
    seasons: dict[int, list[tuple]] = defaultdict(list)

    # 1966-1998: weeks aren't in the file, so derive them from dates. A week runs Tuesday to
    # Monday, so Thursday/Saturday games fall with that weekend and Monday night with the
    # Sunday before it - the way the league numbered them.
    raw: dict[int, list[dict]] = defaultdict(list)
    for r in csv.DictReader(open(SRC / "fivethirtyeight_nfl_games.csv")):
        y = int(r["season"])
        if FIRST <= y <= LAST_538 and r["playoff"] in ("", "0"):
            raw[y].append(r)
    for y, rows in raw.items():
        dates = [dt.date.fromisoformat(r["date"]) for r in rows]
        first = min(dates)
        anchor = first - dt.timedelta(days=(first.weekday() - 1) % 7)  # Tuesday on/before
        for r, d in zip(rows, dates):
            week = (d - anchor).days // 7 + 1
            seasons[y].append(
                (week, CODE[r["team1"]], CODE[r["team2"]], int(r["score1"]), int(r["score2"]), d, flag_for(d), "")
            )

    # 1999+: nflverse, official weeks.
    for r in csv.DictReader(open(SRC / "nflverse_games.csv")):
        y = int(r["season"])
        if y <= LAST_538 or r["game_type"] != "REG":
            continue
        d = dt.date.fromisoformat(r["gameday"])
        hs = int(r["home_score"]) if r["home_score"] not in ("", "NA") else -1
        as_ = int(r["away_score"]) if r["away_score"] not in ("", "NA") else -1
        seasons[y].append(
            (
                int(r["week"]),
                CODE[r["home_team"]],
                CODE[r["away_team"]],
                hs,
                as_,
                d,
                flag_for(d, r["gametime"] or ""),
                (r["stadium"] or "Neutral site").replace(",", " ").replace("|", " ") if r["location"] == "Neutral" else "",
            )
        )

    # 2022 week 17, Bills at Bengals: suspended after Damar Hamlin's cardiac arrest and never
    # finished. Both clubs were scheduled for 17; keep the game on the card so they play them.
    if not any(g[0] == 17 and {g[1], g[2]} == {"cin", "buf"} for g in seasons.get(2022, [])):
        seasons[2022].append((17, "cin", "buf", -1, -1, dt.date(2023, 1, 2), "M", ""))

    lines = [
        "/** Auto-generated by scripts/ingest-schedules.py (FiveThirtyEight 1966-1998, nflverse 1999+). */",
        "/**",
        " * Per season, games joined by '|': week,home,away,homeScore,awayScore,MMDD,flag,neutralSite.",
        " * Scores are what really happened (-1 = not played yet). flag: M Monday, T Thursday,",
        " * S Saturday, F Friday, N Sunday night, empty = Sunday afternoon. neutralSite names the",
        " * stadium for international / neutral games, empty otherwise.",
        " */",
        "export const REAL_SCHEDULES: Record<number, string> = {",
    ]
    for y in sorted(seasons):
        games = sorted(seasons[y], key=lambda g: (g[0], g[5], g[1]))
        # Sanity: nobody plays twice in a week.
        seen: dict[tuple[int, str], int] = {}
        for g in games:
            for t in (g[1], g[2]):
                k = (g[0], t)
                if k in seen:
                    raise SystemExit(f"{y} week {g[0]}: {t} plays twice")
                seen[k] = 1
        body = "|".join(
            f"{g[0]},{g[1]},{g[2]},{g[3]},{g[4]},{g[5].strftime('%m%d')},{g[6]},{g[7]}" for g in games
        )
        lines.append(f'  {y}: "{body}",')
        per_team = defaultdict(int)
        for g in games:
            per_team[g[1]] += 1
            per_team[g[2]] += 1
        counts = sorted(set(per_team.values()))
        print(y, len(games), "games,", len(per_team), "teams, games/team", counts, "weeks", max(g[0] for g in games))
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
