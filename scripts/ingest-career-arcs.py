#!/usr/bin/env python3
"""Build real career arcs (last season, starter years, honors) for every NFL draftee.

Reads the cached PFR draft tables (1966-1979) and nflverse draft_picks.csv (1980+)
already in data/drafts, reusing ingest-draft-classes.py's name normalization so keys
line up with the draft seeds. Writes src/lib/game/data/careerArcs.ts.

Re-run: python3 scripts/ingest-career-arcs.py
"""
from __future__ import annotations

import csv
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "lib" / "game" / "data" / "careerArcs.ts"

spec = importlib.util.spec_from_file_location("idc", ROOT / "scripts" / "ingest-draft-classes.py")
idc = importlib.util.module_from_spec(spec)
spec.loader.exec_module(idc)  # type: ignore[union-attr]


def num(v) -> int:
    try:
        return int(float(str(v).strip() or 0))
    except ValueError:
        return 0


def main() -> None:
    arcs: dict[int, dict[str, list[int]]] = {}

    def put(year: int, first: str, last: str, row: list[int]) -> None:
        bucket = arcs.setdefault(year, {})
        for key in idc.name_keys_of(first, last):
            prev = bucket.get(key)
            # Same name twice in one class: keep the one with the longer career.
            if not prev or row[2] > prev[2]:
                bucket[key] = row

    # 1966-1979: cached PFR draft tables.
    for path in sorted(idc.PFR_DIR.glob("*.htm")):
        html = path.read_text(errors="replace")
        year = num(path.name[:4])
        if not year or year >= 1980:
            continue
        import re

        html = re.sub(r"<!--|-->", "", html)
        for tr in re.findall(r"<tr[^>]*>(.*?)</tr>", html, re.S | re.I):
            cm = idc.cell_map(tr)
            name = cm.get("player") or ""
            if not name or name.lower() in {"player", "rk"}:
                continue
            spl = idc.split_name(name)
            if not spl:
                continue
            put(
                year,
                spl[0],
                spl[1],
                [
                    num(cm.get("year_max")),
                    num(cm.get("years_as_primary_starter")),
                    num(cm.get("g")),
                    num(cm.get("pro_bowls")),
                    num(cm.get("all_pros_first_team")),
                    num(cm.get("age")),
                ],
            )

    # 1980+: nflverse PFR draft picks.
    with open(idc.CSV_PATH, newline="") as fh:
        for r in csv.DictReader(fh):
            year = num(r.get("season"))
            spl = idc.split_name(r.get("pfr_player_name") or "")
            if not year or not spl:
                continue
            put(
                year,
                spl[0],
                spl[1],
                [
                    num(r.get("to")),
                    num(r.get("seasons_started")),
                    num(r.get("games")),
                    num(r.get("probowls")),
                    num(r.get("allpro")),
                    num(r.get("age")),
                ],
            )

    lines = [
        "/** Auto-generated by scripts/ingest-career-arcs.py from cached PFR / nflverse draft tables. */",
        "/** [lastSeason (0 = never played), seasonsAsStarter, games, proBowls, firstTeamAllPros, ageAtDraft] */",
        "export type CareerArcRow = [number, number, number, number, number, number];",
        "/** Keyed by draft year, then first|last lowercased with punctuation stripped. */",
        "export const CAREER_ARCS: Record<number, Record<string, CareerArcRow>> = {",
    ]
    total = 0
    for year in sorted(arcs):
        body = ",".join(f"{json.dumps(k)}:{json.dumps(v, separators=(',', ':'))}" for k, v in sorted(arcs[year].items()))
        lines.append(f"  {year}: {{{body}}},")
        total += len(arcs[year])
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {total} arcs across {len(arcs)} classes -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
